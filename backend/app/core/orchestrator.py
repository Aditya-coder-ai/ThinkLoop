"""Turn Orchestrator coordinating diagnosis, pedagogical strategy, mastery, and streaming."""

import asyncio
import json
import logging
import uuid
from collections.abc import AsyncGenerator
from dataclasses import dataclass
from typing import Any

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from app.config import Settings
from app.core.activity import record_activity
from app.core.clock import Clock, SystemClock
from app.core.diagnoser import DiagnoserService, MisconceptionEventManager
from app.core.strategy import (
    STRATEGY_PROMPT_VERSIONS,
    StrategyContext,
    StrategyType,
    choose_strategy,
    extract_answer_strings,
    render_strategy_prompt,
)
from app.db.models import Concept, ConceptEdge, Mastery, Misconception, Problem, Session, Turn
from app.services.history import HistoryService
from app.services.llm import LLMClient, LLMMessage, LLMTimeoutError
from app.services.mastery import MasteryService

logger = logging.getLogger(__name__)


@dataclass
class OrchestratorEvent:
    """Server-Sent Event generated by the dialogue turn orchestrator."""

    event_type: str  # "strategy" | "mastery_update" | "token" | "done" | "error"
    data: dict[str, Any] | str

    def to_sse(self) -> str:
        """Format event for SSE stream delivery."""
        payload = {"type": self.event_type, "data": self.data}
        return f"data: {json.dumps(payload)}\n\n"


class Orchestrator:
    """Orchestrates a single turn of Socratic STEM dialogue."""

    def __init__(
        self,
        llm_client: LLMClient,
        diagnoser: DiagnoserService,
        mastery_service: MasteryService,
        history_service: HistoryService,
        settings: Settings,
        misconception_mgr: MisconceptionEventManager | None = None,
        clock: Clock | None = None,
    ) -> None:
        self.llm_client = llm_client
        self.diagnoser = diagnoser
        self.mastery_service = mastery_service
        self.history_service = history_service
        self.settings = settings
        self.misconception_mgr = misconception_mgr or MisconceptionEventManager()
        self.clock = clock or SystemClock()

    async def _verify_hook(
        self,
        learner_message: str,
        problem: Problem | None,
    ) -> bool | None:
        """Deterministic math & answer verification hook.

        No-op in Phase 6; implemented deterministically in Phase 7.
        """
        _ = (learner_message, problem)
        return None

    async def _find_weak_prerequisite(
        self,
        db: AsyncSession,
        user_id: uuid.UUID,
        concept_id: str,
    ) -> tuple[str, str, str] | None:
        """Check if any prerequisite of the target concept is weak (< threshold).

        Returns (prereq_id, title, description) or None if no weak prerequisite is found.
        """
        edge_stmt = select(ConceptEdge.source_id).where(ConceptEdge.target_id == concept_id)
        prereq_ids = list((await db.execute(edge_stmt)).scalars().all())
        if not prereq_ids:
            return None

        # Check learner masteries for prerequisites
        mastery_stmt = select(Mastery).where(
            Mastery.user_id == user_id,
            Mastery.concept_id.in_(prereq_ids),
        )
        mastery_rows = {
            m.concept_id: m.p_known for m in (await db.execute(mastery_stmt)).scalars().all()
        }

        weak_id: str | None = None
        for pid in prereq_ids:
            p_known = mastery_rows.get(pid, 0.20)
            if p_known < self.settings.prerequisite_weak_threshold:
                weak_id = pid
                break

        if weak_id:
            c_stmt = select(Concept).where(Concept.id == weak_id)
            weak_concept = (await db.execute(c_stmt)).scalar_one_or_none()
            if weak_concept:
                return (weak_concept.id, weak_concept.title, weak_concept.description)

        return None

    async def run_turn(
        self,
        session: Session,
        concept: Concept,
        learner_message: str,
        user_id: uuid.UUID,
        db: AsyncSession,
        problem: Problem | None = None,
        session_factory: async_sessionmaker[AsyncSession] | None = None,
    ) -> AsyncGenerator[OrchestratorEvent, None]:
        """Execute a full dialogue turn pipeline and yield SSE events.

        Pipeline Stages:
        1. Context loading: Fetch turns history and active problem (if available).
        2. Pedagogical diagnosis: Run fast-model classifier on learner message.
        3. Deterministic verification hook: Phase 7 no-op hook.
        4. Transaction 1 (Pre-Stream Persistence): Atomically commit learner turn,
           misconception event (if detected), and BKT mastery update.
        5. Strategy selection: Pure rule-based selection based on emotion, misconception,
           weak prerequisites, and mastery.
        6. Stream reply: Stream tokens from strong LLM using strategy-specific prompt.
        7. Output guard: Detect potential answer leaks in Socratic/hint mode replies.
        8. Transaction 2 (Post-Stream Persistence): Commit tutor reply turn with
           strategy, prompt version, token usage, and leak_suspected flag.
        """
        # Stage 1: Context loading
        if problem is None:
            prob_stmt = (
                select(Problem)
                .where(Problem.concept_id == concept.id, Problem.is_active.is_(True))
                .limit(1)
            )
            problem = (await db.execute(prob_stmt)).scalar_one_or_none()

        # Query baseline mastery
        m_stmt = select(Mastery).where(
            Mastery.user_id == user_id,
            Mastery.concept_id == concept.id,
        )
        current_mastery_row = (await db.execute(m_stmt)).scalar_one_or_none()
        current_p_known = current_mastery_row.p_known if current_mastery_row else 0.20

        # Check for weak prerequisite gap
        weak_prereq_info = await self._find_weak_prerequisite(
            db=db, user_id=user_id, concept_id=concept.id
        )

        # Stage 2: Pedagogical diagnosis
        diagnosis = await self.diagnoser.diagnose(
            concept=concept,
            learner_message=learner_message,
        )

        # Stage 3: Verification hook (Phase 7 hook)
        verified_correct = await self._verify_hook(
            learner_message=learner_message,
            problem=problem,
        )

        # Stage 4: Transaction 1 (Pre-Stream Persistence)
        # Guarantees that mastery is never updated without the learner turn recorded.
        user_turn = Turn(
            id=uuid.uuid4(),
            session_id=session.id,
            role="user",
            content=learner_message,
            diagnosis=diagnosis.model_dump(),
            prompt_versions={"diagnoser": DiagnoserService.PROMPT_VERSION},
        )
        db.add(user_turn)

        if diagnosis.misconception_id:
            await self.misconception_mgr.record_event(
                db=db,
                session_id=session.id,
                user_id=user_id,
                misconception_id=diagnosis.misconception_id,
                new_status="detected",
                turn_id=user_turn.id,
            )

        mastery_update = await self.mastery_service.record_gradable_turn(
            db=db,
            user_id=user_id,
            concept_id=concept.id,
            understanding=diagnosis.understanding,
            confidence=diagnosis.confidence,
            verified_correct=verified_correct,
        )

        if mastery_update is not None:
            await record_activity(
                session=db,
                user_id=user_id,
                kind="tutor_turn_gradable",
                ref_id=str(user_turn.id),
                ref_type="turn",
                meta={"concept_id": concept.id, "session_id": str(session.id)},
                clock=self.clock,
            )

        await db.commit()
        await db.refresh(user_turn)

        # Stage 5: Strategy Selection
        conflict_prompt: str | None = None
        if diagnosis.misconception_id:
            misc_stmt = select(Misconception).where(Misconception.id == diagnosis.misconception_id)
            misc = (await db.execute(misc_stmt)).scalar_one_or_none()
            if misc:
                conflict_prompt = misc.conflict_prompt

        strategy_ctx = StrategyContext(
            has_weak_prerequisite=weak_prereq_info is not None,
            weak_prerequisite_id=weak_prereq_info[0] if weak_prereq_info else None,
            weak_prerequisite_title=weak_prereq_info[1] if weak_prereq_info else None,
            conflict_prompt=conflict_prompt,
            active_problem_id=problem.id if problem else None,
        )

        effective_mastery = (
            mastery_update.new_p_known if mastery_update is not None else current_p_known
        )
        strategy = choose_strategy(
            mastery=effective_mastery,
            diagnosis=diagnosis,
            context=strategy_ctx,
            settings=self.settings,
        )
        prompt_version = STRATEGY_PROMPT_VERSIONS[strategy]

        # Stage 6: Yield Strategy and Mastery Events
        yield OrchestratorEvent(
            event_type="strategy",
            data={
                "strategy": strategy.value,
                "prompt_version": prompt_version,
            },
        )

        if mastery_update is not None:
            yield OrchestratorEvent(
                event_type="mastery_update",
                data={
                    "concept_id": mastery_update.concept_id,
                    "old": mastery_update.old_p_known,
                    "new": mastery_update.new_p_known,
                    "attempts": mastery_update.attempts,
                    "state": mastery_update.state,
                },
            )

        # Format history and render system prompt
        turns_stmt = select(Turn).where(Turn.session_id == session.id).order_by(Turn.created_at)
        turns = list((await db.execute(turns_stmt)).scalars().all())
        history_messages = self.history_service.format_for_llm(
            turns=turns,
            running_summary=session.summary,
        )

        system_prompt = render_strategy_prompt(
            strategy=strategy,
            concept_title=concept.title,
            concept_description=concept.description,
            problem_statement=problem.statement if problem else None,
            problem_answer_spec=problem.answer_spec if problem else None,
            conflict_prompt=conflict_prompt,
            weak_prerequisite_title=weak_prereq_info[1] if weak_prereq_info else None,
            weak_prerequisite_description=weak_prereq_info[2] if weak_prereq_info else None,
        )
        full_llm_messages: list[LLMMessage] = [
            LLMMessage(role="system", content=system_prompt),
            *history_messages,
        ]

        # Stage 7: Stream reply
        accumulated_tokens: list[str] = []

        async def save_tutor_turn(
            content: str, is_partial: bool, leak_suspected: bool = False
        ) -> Turn:
            turn = Turn(
                id=uuid.uuid4(),
                session_id=session.id,
                role="assistant",
                content=content,
                strategy=strategy.value,
                prompt_versions={
                    "strategy": prompt_version,
                    "partial": is_partial,
                },
                token_usage={"tokens": len(content.split())},
                leak_suspected=leak_suspected,
            )
            if session_factory:
                async with session_factory() as s:
                    s.add(turn)
                    await s.commit()
                    await s.refresh(turn)
            else:
                db.add(turn)
                await db.commit()
                await db.refresh(turn)
            return turn

        try:
            async for token in self.llm_client.stream(
                messages=full_llm_messages,
                model=self.settings.strong_model,
            ):
                accumulated_tokens.append(token)
                yield OrchestratorEvent(event_type="token", data=token)

            full_reply = "".join(accumulated_tokens)

            # Stage 8: Output Guard (Answer Leak Detection)
            leak_suspected = False
            if problem and problem.answer_spec and strategy != StrategyType.WORKED_EXAMPLE:
                target_answers = extract_answer_strings(problem.answer_spec)
                reply_lower = full_reply.lower()
                for ans in target_answers:
                    if len(ans) > 1 and ans.lower() in reply_lower:
                        leak_suspected = True
                        logger.warning(
                            "Answer leak suspected in session=%s for problem=%s. Detected: %s",
                            session.id,
                            problem.id,
                            ans,
                        )
                        break

            # Stage 9: Transaction 2 (Post-Stream Persistence)
            tutor_turn = await save_tutor_turn(
                content=full_reply,
                is_partial=False,
                leak_suspected=leak_suspected,
            )

            yield OrchestratorEvent(
                event_type="done",
                data={
                    "turn_id": str(tutor_turn.id),
                    "session_id": str(session.id),
                    "strategy": strategy.value,
                    "leak_suspected": leak_suspected,
                },
            )

        except (asyncio.CancelledError, GeneratorExit):
            # Client disconnected mid-stream: persist partial reply
            if accumulated_tokens:
                partial_reply = "".join(accumulated_tokens)
                await save_tutor_turn(content=partial_reply, is_partial=True)
            raise

        except Exception as exc:
            logger.error(
                "Error during dialogue turn streaming for session=%s: %s",
                session.id,
                type(exc).__name__,
            )
            err_code = "LLM_TIMEOUT" if isinstance(exc, LLMTimeoutError) else "LLM_ERROR"
            yield OrchestratorEvent(
                event_type="error",
                data={
                    "code": err_code,
                    "message": "Dialogue stream encountered an error.",
                },
            )
